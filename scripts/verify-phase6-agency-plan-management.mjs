import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const checks = []
const check = (name, ok) => checks.push({ name, ok: Boolean(ok) })

const route = read('src/app/module/platformAdmin/platformAdmin.route.ts')
const planAdmin = read('src/app/module/platformAdmin/platformAdmin.tenantPlanManagement.service.ts')
const entitlement = read('src/app/module/entitlement/entitlement.service.ts')
const overrideService = read('src/app/module/tenantEntitlementOverride/tenantEntitlementOverride.service.ts')
const overrideModel = read('src/app/module/tenantEntitlementOverride/tenantEntitlementOverride.model.ts')
const schedule = read('src/app/module/subscription/subscriptionSchedule.service.ts')
const addon = read('src/app/module/leadAddonSubscription/leadAddonSubscription.service.ts')
const tenant360 = read('src/app/module/platformAdmin/platformAdmin.tenant360.service.ts')
const worker = read('src/app/module/cron/phase3.worker.ts')
const migration = read('src/app/db/migrateTenantEntitlementOverrides.ts')
const benefitService = read('src/app/module/subscriptionBenefitPeriod/subscriptionBenefitPeriod.service.ts')

check('Super Admin exact-plan no-charge endpoint exists', route.includes('/subscription/admin-override'))
check('Super Admin scheduled downgrade endpoint exists', route.includes('/subscription/schedule-downgrade'))
check('Super Admin cancellation endpoint exists', route.includes('/subscription/cancellation'))
check('Super Admin paid recurring add-on request endpoint exists', route.includes('/subscription/recurring-addon'))
check('Tenant entitlement override create/read/revoke endpoints exist', route.includes('/entitlement-overrides') && route.includes('/entitlement-overrides/revoke'))
check('No-charge plan changes are explicitly audited', planAdmin.includes('subscription.admin_plan_override_applied') && planAdmin.includes('noCharge: true'))
check('Administrative downgrade uses deferred scheduler', planAdmin.includes('scheduleDowngradeOnOrganization'))
check('Administrative scheduled-change cancellation is audited as Super Admin', planAdmin.includes("actorRole: 'super-admin'"))
check('Normal recurring add-on remains a payment request', planAdmin.includes('createAdminSubscriptionRequest') && addon.includes("status: 'pending_payment'"))
check('Tenant overrides support resource add/set modes', overrideModel.includes("enum: ['add', 'set']"))
check('Tenant override has unique active-per-tenant protection', overrideModel.includes('activeKey') && overrideModel.includes('unique: true'))
check('Tenant overrides are applied after plan/add-on lead capacity resolution', entitlement.indexOf('effectiveLeadLimit = planCapacity + activeTopupLeadAllowance + activeRecurringLeadAllowance') < entitlement.indexOf('const activeTenantOverride = await getActiveTenantEntitlementOverride'))
check('Effective entitlement output carries tenant override snapshot', entitlement.includes('tenantOverride: activeTenantOverride || null'))
check('Override application triggers resource reconciliation', overrideService.includes('reconcileOrganizationEntitlements'))
check('Override expiry reconstructs pre-expiry effective limits', overrideService.includes('effectiveBeforeLimits') && overrideService.includes('applyTenantEntitlementOverride'))
check('Override expiry never deletes resources', !overrideService.includes('.deleteMany(') && !overrideService.includes('.deleteOne('))
check('Scheduled downgrade preserves tenant overrides', schedule.includes('tenantOverrideApplied: true'))
check('Agency 360 exposes active override and effective limits', tenant360.includes('tenantOverrides:') && tenant360.includes('effectiveLimits:'))
check('Agency 360 exposes admin lead adjustment breakdown', tenant360.includes('adminAdjustmentCapacity'))
check('Expired overrides are processed by maintenance worker', worker.includes('applyDueExpirations'))
check('Renewal streak controls target the active paid period rather than a future scheduled period', (benefitService.match(/periodStart: \{ \$lte: now \}/g) || []).length >= 2 && (benefitService.match(/periodEnd: \{ \$gt: now \}/g) || []).length >= 2)
check('Migration does not reassign tenant plan/version', migration.includes('organizationPlanMutation: false') && migration.includes('organizationPlanVersionMutation: false') && migration.includes('historicalPlanLimitMutation: false'))

const failed = checks.filter((item) => !item.ok)
for (const item of checks) console.log(`${item.ok ? 'PASS' : 'FAIL'} ${item.name}`)
console.log(`\n${checks.length - failed.length}/${checks.length} checks passed`)
if (failed.length) process.exit(1)
